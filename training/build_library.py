"""Build the iris texture library used by the renderer.

Source: "Synthetic Iris Image Dataset" (fatdove/Iris_Database on Hugging Face), colour irises generated by a
diffusion model trained on DSLR iris photos (Zhang, Hart, Bi, Fang, Walsh, arXiv:2503.11930). They are
realistic but belong to nobody, which avoids using real people's biometric data.
Licence: MIT on Hugging Face; the authors' README also says "for research purposes". Contact them before any
commercial use.

Each image is unwrapped into a polar strip (angle x radius, pupil edge -> limbus) and saved as a small JPEG,
plus an index of its colours so the renderer can pick the closest texture to the user's eye.

    python build_library.py --n 80 --out ../lib/iris
"""
import argparse
import io
import json
import os
import urllib.request
from concurrent.futures import ThreadPoolExecutor

import cv2
import numpy as np

REPO = "https://huggingface.co/datasets/fatdove/Iris_Database"
NT, NR = 1024, 160


def list_files():
    with urllib.request.urlopen("https://huggingface.co/api/datasets/fatdove/Iris_Database", timeout=60) as r:
        meta = json.load(r)
    return sorted(s["rfilename"] for s in meta["siblings"] if s["rfilename"].endswith(".png"))


def fetch(name):
    with urllib.request.urlopen(f"{REPO}/resolve/main/{name}", timeout=120) as r:
        data = r.read()
    img = cv2.imdecode(np.frombuffer(data, np.uint8), cv2.IMREAD_COLOR)
    return cv2.resize(img, (img.shape[1] // 2, img.shape[0] // 2), interpolation=cv2.INTER_AREA)[..., ::-1]


def unwrap(img):
    """Pupil from the black disk, limbus per angle from the strongest edge, then a polar strip."""
    f = img.astype(np.float32)
    lum = f @ np.array([0.2126, 0.7152, 0.0722], np.float32)
    H, W = lum.shape
    dark = (lum < 22).astype(np.uint8)
    n, lab, stats, cents = cv2.connectedComponentsWithStats(dark)
    if n < 2:
        return None
    # the pupil: the big dark blob closest to the image centre
    best = max(range(1, n), key=lambda k: stats[k, cv2.CC_STAT_AREA] - 0.5 * np.hypot(*(cents[k] - [W / 2, H / 2])))
    pcx, pcy = cents[best]
    pr = np.sqrt(stats[best, cv2.CC_STAT_AREA] / np.pi)
    if pr < 40:
        return None
    # every image in this set uses the same eye template: the iris is a rounded square around the pupil,
    # about 2.35x the pupil radius at its narrowest (the top is flattened by the lid). Stay inside it.
    th = np.linspace(-np.pi, np.pi, NT, endpoint=False)
    lim = np.full(NT, pr * 2.2, np.float32)
    u = (np.arange(NR) + 0.5) / NR
    rho = pr * 1.06 + (lim[:, None] - pr * 1.06) * u[None]
    mx = (pcx + np.cos(th)[:, None] * rho).astype(np.float32)
    my = (pcy + np.sin(th)[:, None] * rho).astype(np.float32)
    strip = np.stack([cv2.remap(np.ascontiguousarray(f[..., c]), mx, my, cv2.INTER_LINEAR) for c in range(3)], -1)
    strip = strip.transpose(1, 0, 2)                         # rows = radius (pupil -> limbus), cols = angle
    # quality: reject strips with sclera/lashes leaking in (very bright or very dark streaks)
    sl = strip @ np.array([0.2126, 0.7152, 0.0722], np.float32)
    if (sl > 248).mean() > 0.02 or (sl < 6).mean() > 0.04:
        return None
    return np.clip(strip, 0, 255).astype(np.uint8), float(pr), float(lim.mean())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=80)
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "lib", "iris"))
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    files = list_files()
    rng = np.random.default_rng(7)
    pick = rng.permutation(len(files))
    index, k = [], 0

    def job(i):
        try:
            return files[i], unwrap(fetch(files[i]))
        except Exception as e:
            return files[i], None

    with ThreadPoolExecutor(6) as ex:
        for start in range(0, len(pick), 24):
            for name, res in ex.map(job, pick[start:start + 24]):
                if res is None or k >= a.n:
                    continue
                strip, pr, lr = res
                fn = f"{k:03d}.jpg"
                cv2.imwrite(os.path.join(a.out, fn), strip[..., ::-1], [cv2.IMWRITE_JPEG_QUALITY, 90])
                bands = [strip[int(b * NR / 6):int((b + 1) * NR / 6)].reshape(-1, 3).mean(0).round(1).tolist() for b in range(6)]
                index.append({"file": fn, "source": name, "pupilRatio": round(pr / lr, 3), "bands": bands})
                k += 1
            print(f"{k}/{a.n}", flush=True)
            if k >= a.n:
                break
    with open(os.path.join(a.out, "index.json"), "w") as fh:
        json.dump({"size": [NT, NR], "credit": "Synthetic Iris Image Dataset, Zhang et al. 2025 (arXiv:2503.11930), "
                   "huggingface.co/datasets/fatdove/Iris_Database", "items": index}, fh)
    print("wrote", len(index), "textures to", a.out)


if __name__ == "__main__":
    main()
